import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';
import { Window } from 'happy-dom';
import { parse, compileScript } from '@vue/compiler-sfc';
import { createStore } from '../server/store.js';
import { createApp as createApi } from '../server/app.js';

test('register a school without previous login, create its teacher account, and isolate a second school', async t => {
  const store = await createStore({ memory: true });
  await store.mutate(data => { for (const key of Object.keys(data)) data[key] = []; });
  let smsCalls = 0;
  const server = createApi(store, { sms: { encryptionKey: Buffer.alloc(32, 8), fetchImpl: async (url, options) => {
    smsCalls++; const number = new URLSearchParams(options.body).get('to');
    return Response.json({ count: 1, list: [{ id: 'test-provider-id', number, submitted_number: number, status: 'QUEUE' }] });
  } } }).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`, window = new Window({ url: base });
  const originalFetch = globalThis.fetch;
  let cookie = '', app;
  for (const key of ['window', 'document', 'navigator', 'Document', 'ShadowRoot', 'Element', 'HTMLElement', 'SVGElement', 'Node']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? window : window[key] });
  globalThis.fetch = async (path, options = {}) => {
    const response = await originalFetch(new URL(path, base), { ...options, headers: { ...options.headers, Cookie: cookie, Origin: base } });
    if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
    return response;
  };
  t.after(async () => { app?.unmount(); globalThis.fetch = originalFetch; await window.happyDOM.close(); await new Promise(resolve => server.close(resolve)); await store.close(); });
  const { descriptor } = parse(await readFile(new URL('./App.vue', import.meta.url), 'utf8'));
  let code = compileScript(descriptor, { id: 'school-access-test', inlineTemplate: true }).content;
  for (const name of ['vue', 'lucide-vue-next']) code = code.replaceAll(`from '${name}'`, `from '${import.meta.resolve(name)}'`).replaceAll(`from "${name}"`, `from "${import.meta.resolve(name)}"`);
  const { default: App } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
  const { createApp, nextTick } = await import('vue');
  const uiErrors = [];
  document.body.innerHTML = '<div id="app"></div>'; app = createApp(App);
  app.config.errorHandler = error => { uiErrors.push(error); };
  app.mount('#app');
  const waitFor = async predicate => {
    for (let i = 0; i < 200; i++) { await nextTick(); if (uiErrors.length) throw uiErrors[0]; if (predicate()) return; await delay(10); }
    throw new Error('Unexpected UI state: ' + document.body.textContent.slice(-1800));
  };
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.includes(text));
  const fill = async (values, selector = '.modal input') => {
    const inputs = [...document.querySelectorAll(selector)]; assert.equal(inputs.length, values.length);
    values.forEach((value, i) => { inputs[i].value = value; inputs[i].dispatchEvent(new window.Event('input', { bubbles: true })); }); await nextTick();
  };
  const submit = (selector = '.modal form') => document.querySelector(selector).dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
  await waitFor(() => button('Dodaj szkołę')); assert.equal(cookie, '');
  button('Dodaj szkołę').click(); await waitFor(() => document.querySelector('.registration-form'));
  assert.equal(document.querySelectorAll('.registration-form input').length, 3, 'registration has only school, username and password');
  await fill(['', 'anna.admin', 'Haslo123456'], '.registration-form input');
  submit('.registration-form'); await waitFor(() => document.querySelector('.registration-form .error'));
  assert.equal((await store.read()).schools.length, 0);
  await fill(['Pierwsza szkoła', 'anna.admin', 'Haslo123456'], '.registration-form input');
  submit('.registration-form'); await waitFor(() => document.querySelector('.app-shell'));
  assert.equal(document.querySelector('.current-school-name').textContent, 'Pierwsza szkoła');
  assert.equal(document.querySelector('#school'), null, 'no school switcher');
  assert.equal(document.querySelector('.add-school-button'), null, 'no adding another school within an account');
  const firstSchool = (await store.read()).schools[0];
  button('Ustawienia').click();
  await waitFor(() => document.querySelector('.sms-settings-form input[type="password"]') && button('Zapisz ustawienia')?.disabled === false);
  const tokenInput = document.querySelector('.sms-settings-form input[type="password"]');
  tokenInput.value = 'test-token-never-a-real-secret'; tokenInput.dispatchEvent(new window.Event('input', { bubbles: true })); await nextTick();
  assert.equal(document.querySelector('.sms-checkbox input').checked, true, 'default is API test mode');
  button('Zapisz ustawienia').click();
  await waitFor(() => document.querySelector('.sms-token-status')?.textContent.includes('Token zapisany') && button('Zapisz ustawienia')?.disabled === false);
  assert.equal(tokenInput.value, '', 'saved token is not displayed again');
  const phoneInput = document.querySelector('.sms-settings-grid input[type="tel"]');
  phoneInput.value = '500600700'; phoneInput.dispatchEvent(new window.Event('input', { bubbles: true })); await nextTick();
  button('Sprawdź API bez wysyłki').click();
  await waitFor(() => document.querySelector('.sms-test-result.test'));
  assert.equal(smsCalls, 1);
  button('Procedury').click(); await nextTick();
  assert.equal(document.querySelectorAll('.record-card').length, 6);
  document.querySelector('.record-card .text-link').click();
  await waitFor(() => document.querySelector('.modal .steps'));
  assert.ok(document.querySelectorAll('.modal .steps li').length >= 4);
  assert.match(document.querySelector('.modal-description').textContent, /PRZYKŁADOWY SZABLON/);
  document.querySelector('.modal [aria-label="Zamknij"]').click(); await nextTick();
  button('Nauczyciele').click(); await nextTick(); button('Dodaj nauczyciela').click();
  await waitFor(() => document.querySelector('.modal input'));
  await fill(['Anna Testowa', 'anna.test@example.com', '+48 500 600 710', 'Matematyka']); submit();
  await waitFor(() => document.querySelector('tbody')?.textContent.includes('Anna Testowa'));
  assert.equal((await store.read()).teachers[0].schoolId, firstSchool.id);
  assert.equal(document.querySelector('a[href="tel:+48500600710"]').textContent, '+48 500 600 710');
  document.querySelector('[aria-label="Edytuj: Anna Testowa"]').click();
  await waitFor(() => document.querySelector('.modal input[type="tel"]'));
  assert.equal(document.querySelector('.modal input[type="tel"]').value, '+48 500 600 710');
  await fill(['Anna Testowa', 'anna.test@example.com', '+48 500 600 711', 'Matematyka']); submit();
  await waitFor(() => !document.querySelector('.modal') && document.querySelector('a[href="tel:+48500600711"]'));
  document.querySelector('[aria-label="Panel nauczyciela: Anna Testowa"]').click();
  await waitFor(() => document.querySelector('.teacher-access-admin'));
  button('Wygeneruj link i klucz').click();
  await waitFor(() => document.querySelector('.teacher-link-value'));
  const personalLink = document.querySelector('.teacher-link-value').value;
  assert.ok(personalLink.startsWith(base + '/nauczyciel#klucz='));
  assert.match(personalLink.split('klucz=')[1], /^[a-f0-9]{64}$/);
  document.querySelector('.modal [aria-label="Zamknij"]').click(); await nextTick();
  button('Import CSV').click();
  await waitFor(() => document.querySelector('.csv-modal input[type="file"]'));
  const csv = 'imię i nazwisko;email;przedmiot;telefon\nZofia CSV;zofia.csv@example.com;Historia;+48 500 600 720\nAnna Testowa;anna.test@example.com;Matematyka;';
  const fileInput = document.querySelector('.csv-modal input[type="file"]');
  Object.defineProperty(fileInput, 'files', { configurable: true, value: [new window.File([csv], 'nauczyciele.csv', { type: 'text/csv' })] });
  fileInput.dispatchEvent(new window.Event('change', { bubbles: true }));
  await waitFor(() => document.querySelectorAll('.csv-preview tbody tr').length === 2);
  assert.equal((await store.read()).teachers.length, 1, 'CSV preview does not save teachers');
  assert.equal(button('Importuj nauczycieli (1)').disabled, false);
  button('Importuj nauczycieli (1)').click();
  await waitFor(() => !document.querySelector('.modal') && document.querySelector('tbody')?.textContent.includes('Zofia CSV'));
  button('Wyślij linki do wszystkich').click();
  await waitFor(() => button('Potwierdzam test API (2)')?.disabled === false);
  assert.ok(document.querySelector('.modal').textContent.includes('2 odbiorców SMS'));
  assert.ok(document.querySelector('.modal').textContent.includes('TRYB TESTOWY'));
  assert.equal(smsCalls, 1, 'opening confirmation does not send SMS');
  button('Anuluj').click(); await nextTick();
  assert.equal(smsCalls, 1, 'canceling does not send SMS');
  button('Wyślij linki do wszystkich').click();
  await waitFor(() => button('Potwierdzam test API (2)')?.disabled === false);
  button('Potwierdzam test API (2)').click();
  await waitFor(() => document.querySelector('.modal')?.textContent.includes('Przyjęto przez SMSAPI: 2 / 2'));
  assert.equal(smsCalls, 3);
  assert.equal(button('Potwierdzam test API'), undefined);
  document.querySelector('.modal [aria-label="Zamknij"]').click(); await nextTick();
  assert.equal((await store.read()).teachers.length, 2);
  button('Użytkownicy').click(); await nextTick(); button('Dodaj użytkownika').click();
  await waitFor(() => document.querySelector('.modal input'));
  await fill(['Michał Nauczyciel', 'michal.nauczyciel', '', '+48 500 600 700', 'Haslo123456']); submit();
  await waitFor(() => !document.querySelector('.modal') && document.querySelector('tbody')?.textContent.includes('michal.nauczyciel'));
  assert.equal(document.querySelector('a[href="tel:+48500600700"]').textContent, '+48 500 600 700');
  document.querySelector('[aria-label="Edytuj: Michał Nauczyciel"]').click();
  await waitFor(() => document.querySelector('.modal input[type="tel"]'));
  assert.equal(document.querySelector('.modal input[type="tel"]').value, '+48 500 600 700');
  await fill(['Michał Nauczyciel', 'michal.nauczyciel', '', '+48 500 600 701', '']); submit();
  await waitFor(() => !document.querySelector('.modal') && document.querySelector('a[href="tel:+48500600701"]'));
  document.querySelector('[aria-label="Wyloguj"]').click(); await waitFor(() => document.querySelector('.login-page'));
  await fill(['michal.nauczyciel', 'Haslo123456'], '.login-form form input'); submit('.login-form form');
  await waitFor(() => document.querySelector('.app-shell'));
  assert.equal(button('Użytkownicy'), undefined);
  assert.equal(button('Ustawienia'), undefined);
  assert.equal(document.querySelector('.current-school-name').textContent, 'Pierwsza szkoła');
  button('Nauczyciele').click(); await nextTick(); assert.equal(button('Dodaj nauczyciela'), undefined);
  assert.equal(button('Import CSV'), undefined);
  assert.equal(button('Wyślij linki do wszystkich'), undefined);
  document.querySelector('[aria-label="Wyloguj"]').click(); await waitFor(() => document.querySelector('.login-page'));
  button('Dodaj szkołę').click(); await waitFor(() => document.querySelector('.registration-form'));
  await fill(['Druga szkoła', 'piotr.admin', 'testowe-haslo-456'], '.registration-form input');
  submit('.registration-form'); await waitFor(() => document.querySelector('.app-shell'));
  assert.equal(document.querySelector('.current-school-name').textContent, 'Druga szkoła');
  assert.equal(document.body.textContent.includes('Pierwsza szkoła'), false);
  button('Nauczyciele').click(); await nextTick(); assert.equal(document.body.textContent.includes('Anna Testowa'), false);
  assert.equal((await store.read()).schools.length, 2);
});
